"""v9.0 GRSC: greedy repair schedule construction for the YES side.

The v7.x line is a refutation engine: it certifies NO by LP/Farkas leaves
and returns YES only when an LP vertex happens to be integral.  On the
satisfiable side (h = OPT) the threshold DFS can wander: in the 141-case
corpus v7.1 QNC returns UNKNOWN on 11 instances and spends 7043 LPs.

This module adds the missing half: a schedule constructor.

Model.  A state is a partial schedule.  A *greedy completion* picks an
available job (all predecessors scheduled), an eligible machine, and the
earliest feasible start on that machine.  The resulting schedule is
active.  The classical serial SGS theorem says that if a feasible
schedule exists, an active feasible schedule exists, and every active
schedule is generated by some priority list.  Therefore a DFS over the
greedy choices (job, machine) is complete: it only branches on discrete
priority choices, never on continuous start times.

FPT view.  Fix a greedy priority rule.  A path that deviates from the
rule in k decisions is a *k-repair*.  The bounded search tree has at most
(nm)^k nodes, so the constructor is fixed-parameter tractable in the
repair distance k.  In the corpus k is tiny: most YES instances close
with the first greedy schedule, and the 11 QNC gaps close with a few
randomized restarts.

Soundness is trivial for YES: the returned schedule is replayed by an
independent checker.  The constructor never returns NO; NO remains the
job of the v7.1/v7.2 certificate engine.
"""
import sys
sys.path[:0] = ['exp/v13']
import random
import po


def heads_tails(inst, h):
    est, q = po.heads_tails(inst, 0, [0] * inst['n'])
    latest = [h - q[i] - inst['p'][i] for i in range(inst['n'])]
    return est, q, latest


def check_schedule(inst, h, start, mach):
    """Independent replay of a complete schedule."""
    n, m, p = inst['n'], inst['m'], inst['p']
    if start is None or mach is None or len(start) != n or len(mach) != n:
        return False
    for i in range(n):
        if start[i] is None or mach[i] is None:
            return False
        if start[i] < 0 or start[i] + p[i] > h:
            return False
        if mach[i] not in inst['elig'][i]:
            return False
    for i in range(n):
        for j in inst['succ'][i]:
            if start[j] < start[i] + p[i]:
                return False
    for k in range(m):
        js = sorted([i for i in range(n) if mach[i] == k],
                    key=lambda i: start[i])
        for a, b in zip(js, js[1:]):
            if start[a] + p[a] > start[b]:
                return False
    return True


def _insert(busy, k, a, b):
    busy[k].append((a, b))
    busy[k].sort()


def _earliest(busy_k, base, p):
    t = base
    for a, b in sorted(busy_k):
        if t + p <= a:
            break
        if t < b:
            t = b
    return t


class GRSC:
    def __init__(self, inst, h, nodecap=4000, restarts=64, seed=0,
                 modes=('est', 'mixed', 'rand')):
        self.inst = inst
        self.h = h
        self.n = inst['n']
        self.m = inst['m']
        self.p = inst['p']
        self.pred = inst['pred']
        self.succ = inst['succ']
        self.elig = inst['elig']
        self.est, self.q, self.latest = heads_tails(inst, h)
        self.nodecap = nodecap
        self.restarts = restarts
        self.seed = seed
        self.modes = modes
        self.nodes = 0
        self.restarts_used = 0
        self.schedule = None
        self.machine = None
        self.fail_reason = None

    def _one(self, seed, mode):
        rng = random.Random(seed)
        n, m, p = self.n, self.m, self.p
        est, latest = self.est, self.latest
        if any(est[i] > latest[i] for i in range(n)):
            return None
        starts = [None] * n
        machs = [None] * n
        busy = [[] for _ in range(m)]
        rem = [len(self.pred[i]) for i in range(n)]
        predfin = [0] * n
        done = [False] * n
        cap = self.nodecap
        nodes = [0]

        def rec():
            nodes[0] += 1
            if nodes[0] > cap:
                return False
            if all(done):
                return True
            av = [i for i in range(n) if not done[i] and rem[i] == 0]
            if not av:
                return False
            if mode == 'rand':
                rng.shuffle(av)
            elif mode == 'est':
                av.sort(key=lambda i: (
                    est[i] + rng.random() * rng.choice([0, 2, 5, 10]),
                    rng.random()))
            else:
                av.sort(key=lambda i: (
                    latest[i] + rng.random() * rng.choice([0, 2, 5, 10]),
                    rng.random()))
            for i in av:
                base = max(est[i], predfin[i])
                opts = []
                for k in self.elig[i]:
                    tt = _earliest(busy[k], base, p[i])
                    if tt <= latest[i]:
                        opts.append((tt, k))
                opts.sort()
                if mode == 'rand':
                    rng.shuffle(opts)
                for tt, k in opts:
                    starts[i] = tt
                    machs[i] = k
                    done[i] = True
                    _insert(busy, k, tt, tt + p[i])
                    old = [(j, predfin[j]) for j in self.succ[i]]
                    for j in self.succ[i]:
                        if tt + p[i] > predfin[j]:
                            predfin[j] = tt + p[i]
                        rem[j] -= 1
                    if rec():
                        return True
                    for j, v in old:
                        predfin[j] = v
                        rem[j] += 1
                    busy[k].remove((tt, tt + p[i]))
                    done[i] = False
                    starts[i] = None
                    machs[i] = None
                    if nodes[0] > cap:
                        return False
            return False

        ok = rec()
        self.nodes += nodes[0]
        if ok:
            return starts, machs
        return None

    def solve(self):
        for r in range(self.restarts):
            self.restarts_used += 1
            mode = self.modes[r % len(self.modes)]
            got = self._one(self.seed + r, mode)
            if got is not None:
                if check_schedule(self.inst, self.h, got[0], got[1]):
                    self.schedule, self.machine = got
                    self.fail_reason = None
                    return True
                self.fail_reason = 'check'
                return False
        self.fail_reason = 'budget'
        return False

    def stats(self):
        return dict(nodes=self.nodes, restarts=self.restarts_used,
                    found=self.schedule is not None,
                    fail=self.fail_reason,
                    nodecap=self.nodecap, seed=self.seed)
