#!/usr/bin/env python3
"""Round-2 probe: how reliable is a 32-task mean-success leaderboard?

The only public per-task table is the teaser generated by gen_leaderboard.py.
We use its *structure* (8 models x 32 tasks) as a noise model: treat each
published task success rate as the true rate and resample n episodes/task.
This is a statistical sensitivity analysis, NOT benchmark evidence.

Outputs exp/reliability_rank_stability.json
"""
import json
import os

import numpy as np

EXP = os.path.dirname(os.path.abspath(__file__))
R = 20000
N_LIST = [1, 3, 5, 10, 20, 30, 50, 100, 300, 700, 1000]
RNG = np.random.default_rng(20261118)


def load_matrix():
    d = json.load(open(os.path.join(EXP, "r16_leaderboard_data.json")))
    tasks = d["tasks"]
    models = [m["model_name"] for m in d["models"]]
    p = np.array([[t["success_rate"] / 100.0 for t in m["task_metrics"]]
                  for m in d["models"]])
    return models, tasks, p


def ranks(scores):
    order = np.argsort(-scores, kind="stable")
    out = np.empty_like(order)
    out[order] = np.arange(len(scores))
    return out


def kendall_tau(a, b):
    n = len(a)
    num = 0
    for i in range(n):
        for j in range(i + 1, n):
            num += np.sign(a[i] - a[j]) * np.sign(b[i] - b[j])
    return num / (n * (n - 1) / 2)


def main():
    models, tasks, p = load_matrix()
    obs_score = p.mean(axis=1) * 100
    obs_rank = ranks(obs_score)
    top1 = int(np.argmin(obs_rank))
    second = int(np.argsort(-obs_score, kind="stable")[1])
    out = {
        "source": "exp/r16_leaderboard_data.json (teaser, generated_from=gen_leaderboard.py)",
        "warning": "structural sensitivity analysis on a randomly-generated teaser; not benchmark evidence",
        "n_models": len(models), "n_tasks": len(tasks),
        "models": models,
        "observed_avg_success": {m: round(float(s), 2) for m, s in zip(models, obs_score)},
        "observed_rank": {m: int(r + 1) for m, r in zip(models, obs_rank)},
        "top1": models[top1],
        "top1_minus_2nd_pp": round(float(obs_score[top1] - obs_score[second]), 3),
        "design": {"bootstrap_reps": R, "n_episodes_per_task_per_model": N_LIST},
        "by_n": {},
    }

    for n in N_LIST:
        exact = 0
        top1_ok = 0
        taus = []
        shifts = np.zeros(len(models))
        avg_scores = []
        pair_flips = {}
        for _ in range(R):
            x = RNG.binomial(n, p) / n
            score = x.mean(axis=1) * 100
            avg_scores.append(score)
            r = ranks(score)
            exact += int(np.array_equal(r, obs_rank))
            top1_ok += int(r[top1] == 0)
            taus.append(kendall_tau(-score, -obs_score))
            shifts += np.abs(r - obs_rank)
            # adjacent pairs in the observed order
            order = np.argsort(obs_rank)
            for a, b in zip(order[:-1], order[1:]):
                key = f"{models[a]}>{models[b]}"
                pair_flips[key] = pair_flips.get(key, 0) + int(r[a] > r[b])
        out["by_n"][str(n)] = {
            "p_exact_ranking": round(exact / R, 4),
            "p_top1_correct": round(top1_ok / R, 4),
            "mean_kendall_tau_vs_observed": round(float(np.mean(taus)), 4),
            "mean_abs_rank_shift": round(float(shifts.mean() / R), 3),
            "max_model_mean_abs_rank_shift": round(float(shifts.max() / R), 3),
            "adjacent_pair_flip_prob": {
                k: round(v / R, 4) for k, v in pair_flips.items()},
            "std_of_avg_score_pp": round(
                float(np.mean(np.std(np.array(avg_scores), axis=0))), 3),
        }
        print(f"n={n:4d}  P(exact)={exact/R:.3f}  P(top1)={top1_ok/R:.3f}  "
              f"tau={np.mean(taus):.3f}  mean|dRank|={shifts.mean()/R:.2f}")

    # Power to tell top1 from 2nd as a function of n (paired task structure).
    power = {}
    for n in [10, 30, 50, 100, 300, 700, 1000, 2000]:
        wins = 0
        for _ in range(R):
            x = RNG.binomial(n, p) / n
            s = x.mean(axis=1)
            wins += int(s[top1] > s[second])
        power[str(n)] = round(wins / R, 4)
    out["power_top1_over_2nd"] = power
    print("power top1>2nd:", power)

    # Minimum detectable difference (MDD) at 80% power, normal approximation.
    # Variance of the task-averaged rate is sum_t p_t(1-p_t)/n / T^2.
    var_per_task = p * (1 - p)
    def se_pp(n, i, j=None):
        v = var_per_task[i] if j is None else var_per_task[i] + var_per_task[j]
        return float(np.sqrt(v.sum() / n) / len(tasks) * 100)
    out["se_top1_minus_2nd_pp"] = {
        str(n): round(se_pp(n, top1, second), 3)
        for n in [10, 30, 100, 300, 1000]}
    out["mdd80_top1_vs_2nd_pp"] = {
        str(n): round(2.802 * se_pp(n, top1, second), 3)
        for n in [10, 30, 100, 300, 1000]}
    out["se_avg_model_pp_n1000"] = round(
        float(np.mean([se_pp(1000, i) for i in range(len(models))])), 3)
    out["mdd80_avg_model_pp_n1000"] = round(
        float(2.802 * np.mean([se_pp(1000, i) for i in range(len(models))])), 3)

    json.dump(out, open(os.path.join(EXP, "reliability_rank_stability.json"), "w"),
              indent=1, ensure_ascii=False)
    print("wrote exp/reliability_rank_stability.json")


if __name__ == "__main__":
    main()
